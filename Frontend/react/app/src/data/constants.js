const PROD_SERVER_HOST = import.meta.env.VITE_PROD_SERVER_HOST
const PROD_SERVER_PORT = import.meta.env.VITE_PROD_SERVER_PORT

const DEVELOPMENT_SERVER_HOST = import.meta.env.VITE_DEVELOPMENT_SERVER_HOST || "localhost"
const DEVELOPMENT_DJANGO_SERVER_PORT = import.meta.env.VITE_DEVELOPMENT_DJANGO_SERVER_PORT || "1972"
const DEVELOPMENT_FASTAPI_SERVER_PORT = import.meta.env.VITE_DEVELOPMENT_FASTAPI_SERVER_PORT || "1974"

export const DEVELOPMENT = import.meta.env.VITE_DEVELOPMENT || "0"

// Development
export const DEVELOPMENT_FASTAPI_FETCH_URL = import.meta.env.VITE_DEVELOPMENT_FASTAPI_FETCH_URL || `http://${DEVELOPMENT_SERVER_HOST}:${DEVELOPMENT_FASTAPI_SERVER_PORT}/`
export const DEVELOPMENT_DJANGO_FETCH_URL = import.meta.env.VITE_DEVELOPMENT_DJANGO_FETCH_URL || `http://${DEVELOPMENT_SERVER_HOST}:${DEVELOPMENT_DJANGO_SERVER_PORT}/`
export const DEVELOPMENT_WEBSOCKET_DJANGO_URL = `ws://${DEVELOPMENT_SERVER_HOST}:${DEVELOPMENT_DJANGO_SERVER_PORT}/ws/v1/`

// Prod
export const PROD_FETCH_URL = import.meta.env.VITE_PROD_FETCH_URL
